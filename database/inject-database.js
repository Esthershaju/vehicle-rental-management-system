    sql.push("  `customer_id` INT NOT NULL,");
    sql.push("  `vehicle_id` INT NOT NULL,");
    sql.push("  `rental_date` DATE NOT NULL,");
    sql.push("  `return_date` DATE NULL,");
    sql.push("  `total_amount` DECIMAL(10,2) NULL,");
