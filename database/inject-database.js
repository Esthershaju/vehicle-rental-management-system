    sql.push("CREATE TABLE IF NOT EXISTS `customers` (");
    sql.push("  `customer_id` INT PRIMARY KEY AUTO_INCREMENT,");
    sql.push("  `name` VARCHAR(100) NOT NULL,");
    sql.push("  `phone` VARCHAR(15) NOT NULL,");
    sql.push("  `email` VARCHAR(100) UNIQUE NOT NULL,");
    sql.push("  `password` VARCHAR(255) NOT NULL DEFAULT '',");
    sql.push("  `address` VARCHAR(255) NULL,");
    sql.push("  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
    sql.push(") ENGINE=InnoDB;\n");

