    sql.push("CREATE DATABASE IF NOT EXISTS `" + conn.database + "`");
    sql.push("  CHARACTER SET " + (conn.charset || "utf8mb4"));
    sql.push("  COLLATE " + (conn.collation || "utf8mb4_unicode_ci") + ";\n");
    sql.push("USE `" + conn.database + "`;\n");

    // 4.2 Drop tables if fresh mode
    if (isFresh) {
      sql.push("SET FOREIGN_KEY_CHECKS = 0;");
      sql.push("DROP TABLE IF EXISTS `rentals`;");
      sql.push("DROP TABLE IF EXISTS `customers`;");
      sql.push("DROP TABLE IF EXISTS `vehicles`;");
      sql.push("DROP TABLE IF EXISTS `users`;");
      sql.push("SET FOREIGN_KEY_CHECKS = 1;\n");
    }

    // 4.3 Table: users
    sql.push("CREATE TABLE IF NOT EXISTS `users` (");
    sql.push("  `user_id` INT PRIMARY KEY AUTO_INCREMENT,");
    sql.push("  `username` VARCHAR(50) UNIQUE NOT NULL,");
    sql.push("  `password` VARCHAR(255) NOT NULL,");
    sql.push("  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
    sql.push(") ENGINE=InnoDB;\n");

    // 4.4 Table: vehicles
    sql.push("CREATE TABLE IF NOT EXISTS `vehicles` (");
    sql.push("  `vehicle_id` INT PRIMARY KEY AUTO_INCREMENT,");
    sql.push("  `vehicle_number` VARCHAR(20) UNIQUE NOT NULL,");
    sql.push("  `vehicle_name` VARCHAR(100) NOT NULL,");
    sql.push("  `vehicle_type` VARCHAR(50) NOT NULL,");
    sql.push("  `brand` VARCHAR(50) NULL,");
    sql.push("  `model` VARCHAR(50) NULL,");
    sql.push("  `rental_price` DECIMAL(10,2) NOT NULL,");
    sql.push("  `availability_status` VARCHAR(20) DEFAULT 'AVAILABLE',");
    sql.push("  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
    sql.push(") ENGINE=InnoDB;\n");

